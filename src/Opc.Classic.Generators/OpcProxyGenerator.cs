        {
            sb.Append(indent).Append("                return ").Append(DecodeResponseName(method)).Append('(').Append(resultLocal).AppendLine(".ResponsePayload);");
        }

        sb.Append(indent).AppendLine("            }");
        sb.Append(indent).AppendLine("            finally");
        sb.Append(indent).AppendLine("            {");
        sb.Append(indent).Append("                global::System.Buffers.ArrayPool<byte>.Shared.Return(").Append(bufferLocal).AppendLine(");");
        sb.Append(indent).AppendLine("            }");
        sb.Append(indent).AppendLine("        }");
    }

    private static void EmitInvokeCoreSignature(StringBuilder sb, string indent, MethodModel method)
    {
        sb.Append(indent).Append("        static async "); if (ResponseItemCount(method) > 0) { sb.Append("global::System.Threading.Tasks.Task<").Append(ResponseValueType(method)).Append('>'); } else { sb.Append("global::System.Threading.Tasks.Task"); } sb.Append(' ').Append(InvokeCoreName(method)).AppendLine("(");
    }
    private static void EmitDecodeResponseLocalFunction(StringBuilder sb, string indent, MethodModel method, string responsePayloadLocal, string responseSpanLocal, string readerLocal)
    {
        sb.Append(indent).Append("        static ").Append(ResponseValueType(method)).Append(' ').Append(DecodeResponseName(method)).Append("(global::System.ReadOnlyMemory<byte> ").Append(responsePayloadLocal).AppendLine(")"); sb.Append(indent).AppendLine("        {"); sb.Append(indent).Append("            var ").Append(responseSpanLocal).Append(" = ").Append(responsePayloadLocal).AppendLine(".Span;"); sb.Append(indent).Append("            var ").Append(readerLocal).Append(" = new global::Opc.Classic.Ndr.NdrReader(").Append(responseSpanLocal).AppendLine(");"); EmitCodecReadResponse(sb, indent, readerLocal, method, responsePayloadLocal, responseSpanLocal); sb.Append(indent).AppendLine("        }");
    }
    private static string InvokeCoreName(MethodModel method) => "__opcInvoke" + method.Name + "CoreAsync";

    private static string DecodeResponseName(MethodModel method) => "__opcDecode" + method.Name + "Response";

    private static void EmitFailureCheck(StringBuilder sb, string indent, string resultLocal)
    {
        sb.Append(indent).Append("        if (").Append(resultLocal).AppendLine(".IsFailure)");
        sb.Append(indent).AppendLine("        {");
        sb.Append(indent).Append("            throw new global::Opc.Classic.OpcException(new global::Opc.Classic.OpcResultId(")
            .Append(resultLocal).AppendLine(".Hresult, null));");
        sb.Append(indent).AppendLine("        }");
    }

    private static string? FindUnsupportedMarshallingType(
        IEnumerable<ParameterModel> parameters,
        TaskReturnKind taskReturnKind,
        string? taskResultMarshallingType,
        bool taskResultIsOpcInterface,
        string? declaringNamespace,
        out string? unsupportedRefOutMarshallingType,
        out UnsupportedMarshallingKind unsupportedMarshallingKind,
        out string? unsupportedParameterName)
    {
        unsupportedRefOutMarshallingType = null;
        unsupportedMarshallingKind = UnsupportedMarshallingKind.None;
        unsupportedParameterName = null;
        foreach (var parameter in parameters)
        {
            if (parameter.IsCancellationToken)
            {
                continue;
            }

            if (parameter.IsRequestValue && !CanWriteType(parameter.MarshallingType, parameter.IsOpcInterface, declaringNamespace))
            {
                // Unique-pointer parameters (Nullable<T> or [OpcUniquePointer]) are
                // accepted as long as the underlying value type has a codec; the
                // pointer wrapping is handled by the emitter.
                if (parameter.IsUniquePointer
                    && parameter.UnderlyingValueType is { } underlying
                    && CanWriteType(underlying, isOpcInterface: false, declaringNamespace))
                {
                    continue;
                }

                if (parameter.RefKind == RefKind.Ref || parameter.RefKind == RefKind.Out)
                {
                    unsupportedRefOutMarshallingType = parameter.MarshallingType;
                    return null;
                }

                unsupportedMarshallingKind = UnsupportedMarshallingKind.Parameter;
                unsupportedParameterName = parameter.Name;
                return parameter.MarshallingType;
            }

            if (parameter.IsResponseValue && !CanReadType(parameter.MarshallingType, parameter.IsOpcInterface, declaringNamespace))
            {
                unsupportedRefOutMarshallingType = parameter.MarshallingType;
                return null;
            }
        }

        if (taskReturnKind == TaskReturnKind.TaskOfT &&
            (taskResultMarshallingType is null || !CanReadType(taskResultMarshallingType, taskResultIsOpcInterface, declaringNamespace)))
        {
            unsupportedMarshallingKind = UnsupportedMarshallingKind.Return;
            return taskResultMarshallingType ?? "<unknown>";
        }

        return null;
    }
    private static void EmitCodecWrite(
        StringBuilder sb,
        string indent,
        string writerLocal,
        ParameterModel parameter,
        MethodModel method)
    {
        string statementIndent = indent + "                ";

        if (parameter.IsUniquePointer && TryEmitUniquePointerWrite(sb, statementIndent, writerLocal, parameter, method))
        {
            return;
        }

        if (TryGetCodec(parameter.MarshallingType, method.DeclaringNamespace, out var codec))
        {
            if (codec.IsArray)
            {
                // [in] DWORD N + [in, size_is(N)] T* arr — emit the standalone
                // count field BEFORE the array's own NDR max_count prefix.
                if (parameter.EmitArrayCount)
                {
                    sb.Append(statementIndent).Append(writerLocal).Append(".WriteUInt32((uint)(").Append(parameter.Name).AppendLine("?.Length ?? 0));");
                }

                if (parameter.IsUniquePointer)
                {
                    sb.Append(statementIndent).Append(writerLocal).Append(".WriteUInt32(").Append(parameter.Name).AppendLine(" is null ? 0u : 0x00020000u);");
                    sb.Append(statementIndent).Append("if (").Append(parameter.Name).AppendLine(" is not null)");
                    sb.Append(statementIndent).AppendLine("{");
                    EmitArrayCodecWrite(sb, statementIndent + "    ", writerLocal, parameter.Name, codec, method.ParameterNames, parameter.DeferredElements);
                    sb.Append(statementIndent).AppendLine("}");
                    return;
                }
                EmitArrayCodecWrite(sb, statementIndent, writerLocal, parameter.Name, codec, method.ParameterNames, parameter.DeferredElements);
                return;
            }

            sb.Append(statementIndent).Append(FormatWriteExpression(codec, writerLocal, parameter.Name)).AppendLine(";");
            return;
        }

        sb.Append(statementIndent).Append(writerLocal).AppendLine(".WriteRawBytes(global::System.ReadOnlySpan<byte>.Empty);");
    }

    /// <summary>
    /// Emits the NDR unique-pointer wire prefix + value for a parameter tagged
    /// with [OpcUniquePointer] (per DCE 1.1 §14.3.10). Handles three shapes:
    ///   - IOpcInterfaceRef → MInterfacePointer wrapping (MS-DCOM §2.2.1.10).
    ///   - Nullable&lt;T&gt; → HasValue gates the value write.
    ///   - non-nullable scalar with explicit [OpcUniquePointer] → always present.
    /// Returns true if it handled the parameter; false if no matching codec
    /// shape was found (caller falls back to the array/inline path).
    /// </summary>
    private static bool TryEmitUniquePointerWrite(
        StringBuilder sb,
        string statementIndent,
        string writerLocal,
        ParameterModel parameter,
        MethodModel method)
    {
        if (string.Equals(parameter.MarshallingType, "global::Opc.Classic.Dcom.IOpcInterfaceRef", System.StringComparison.Ordinal))
        {
            sb.Append(statementIndent).Append("global::Opc.Classic.Dcom.OpcMInterfacePointerCodec.Write(ref ").Append(writerLocal).Append(", ").Append(parameter.Name).AppendLine(");");
            return true;
        }

        string codecKey = parameter.UnderlyingValueType ?? parameter.MarshallingType;
        if (!TryGetCodec(codecKey, method.DeclaringNamespace, out var underlyingCodec) || underlyingCodec.IsArray)
        {
            return false;
        }

        if (parameter.UnderlyingValueType is not null)
        {
            sb.Append(statementIndent).Append(writerLocal).Append(".WriteUInt32(").Append(parameter.Name).AppendLine(".HasValue ? 0x00020000u : 0u);");
            sb.Append(statementIndent).Append("if (").Append(parameter.Name).AppendLine(".HasValue)");
            sb.Append(statementIndent).AppendLine("{");
            sb.Append(statementIndent).Append("    ").Append(FormatWriteExpression(underlyingCodec, writerLocal, parameter.Name + ".Value")).AppendLine(";");
            sb.Append(statementIndent).AppendLine("}");
        }
        else
        {
            sb.Append(statementIndent).Append(writerLocal).AppendLine(".WriteUInt32(0x00020000u);");
            sb.Append(statementIndent).Append(FormatWriteExpression(underlyingCodec, writerLocal, parameter.Name)).AppendLine(";");
        }
        return true;
    }

    private static void EmitArrayCodecWrite(
        StringBuilder sb,
        string statementIndent,
        string writerLocal,
        string parameterName,
        CodecEmitter codec,
        ImmutableArray<string> parameterNames,
        bool deferredElements = false)
    {
        // [OpcDeferredElements] on a string[] parameter switches to the
        // C706 §14.3.12.3 two-pass layout: max_count + per-element referent
        // (no body), then per-element conformant-varying string body. This
        // is the wire shape real Windows DCOM peers expect for IDL
        // [in, size_is(N)] LPCWSTR* arrays under pointer_default(unique).
        if (deferredElements && IsStringElementCodec(codec))
        {
            string idxLocal = UniqueLocalName(parameterNames, "__opcIdx", writerLocal, parameterName);
            sb.Append(statementIndent).Append(writerLocal).Append(".WriteUInt32((uint)(").Append(parameterName).AppendLine("?.Length ?? 0));");
            sb.Append(statementIndent).Append("if (").Append(parameterName).AppendLine(" is not null)");
            sb.Append(statementIndent).AppendLine("{");
            sb.Append(statementIndent).Append("    for (int ").Append(idxLocal).Append(" = 0; ").Append(idxLocal).Append(" < ").Append(parameterName).Append(".Length; ").Append(idxLocal).AppendLine("++)");
            sb.Append(statementIndent).AppendLine("    {");
            sb.Append(statementIndent).Append("        ").Append(writerLocal).Append(".WriteUInt32(").Append(parameterName).Append('[').Append(idxLocal).AppendLine("] is null ? 0u : 0x00020000u);");
            sb.Append(statementIndent).AppendLine("    }");
            sb.Append(statementIndent).Append("    for (int ").Append(idxLocal).Append(" = 0; ").Append(idxLocal).Append(" < ").Append(parameterName).Append(".Length; ").Append(idxLocal).AppendLine("++)");
            sb.Append(statementIndent).AppendLine("    {");
            sb.Append(statementIndent).Append("        if (").Append(parameterName).Append('[').Append(idxLocal).Append("] is string ").Append(idxLocal).AppendLine("Str)");
            sb.Append(statementIndent).AppendLine("        {");
            sb.Append(statementIndent).Append("            ").Append(writerLocal).Append(".WriteUnicodeString(").Append(idxLocal).AppendLine("Str);");
            sb.Append(statementIndent).AppendLine("        }");
            sb.Append(statementIndent).AppendLine("    }");
            sb.Append(statementIndent).AppendLine("}");
            return;
        }

        string itemLocal = UniqueLocalName(parameterNames, "__opcItem", writerLocal, parameterName);
        sb.Append(statementIndent).Append(writerLocal).Append(".WriteUInt32((uint)(").Append(parameterName).AppendLine("?.Length ?? 0));");
        sb.Append(statementIndent).Append("if (").Append(parameterName).AppendLine(" != null)");
        sb.Append(statementIndent).AppendLine("{");
        sb.Append(statementIndent).Append("    foreach (var ").Append(itemLocal).Append(" in ").Append(parameterName).AppendLine(")");
        sb.Append(statementIndent).AppendLine("    {");
        sb.Append(statementIndent).Append("        ").Append(FormatWriteExpression(codec, writerLocal, itemLocal)).AppendLine(";");
        sb.Append(statementIndent).AppendLine("    }");
        sb.Append(statementIndent).AppendLine("}");
    }

    /// <summary>Detects the string-array codec by inspecting its element-write expression for the WriteUnicodeStringPtr inline-pointer pattern.</summary>
    private static bool IsStringElementCodec(CodecEmitter codec) =>
        codec.WriteExpression.Contains("WriteUnicodeStringPtr", System.StringComparison.Ordinal);

    private static void EmitCodecReadResponse(
        StringBuilder sb,
        string indent,
        string readerLocal,
        MethodModel method,
        string responsePayloadLocal,
        string responseSpanLocal)
    {
        string statementIndent = indent + "            ";
        int itemIndex = 0;
        if (method.TaskReturnKind == TaskReturnKind.TaskOfT)
        {
            EmitCodecReadLocal(
                sb,
                statementIndent,
                readerLocal,
                method,
                method.TaskResultType!,
                method.TaskResultMarshallingType!,
                method.TaskResultIsOpcInterface,
                method.TaskResultIsUniquePointer,
                ResponseValueLocalName(itemIndex),
                responsePayloadLocal,
                responseSpanLocal);
            itemIndex++;
        }

        foreach (var parameter in method.Parameters)
        {
            if (!parameter.IsResponseValue)
            {
                continue;
            }

            EmitCodecReadLocal(
                sb,
                statementIndent,
                readerLocal,
                method,
                parameter.DeclaredType,
                parameter.MarshallingType,
                parameter.IsOpcInterface,
                parameter.IsUniquePointer,
                ResponseValueLocalName(itemIndex),
                responsePayloadLocal,
                responseSpanLocal);
            itemIndex++;
        }

        EmitDecodedResponseReturn(sb, statementIndent, method);
    }

    private static void EmitCodecReadLocal(
        StringBuilder sb,
        string statementIndent,
        string readerLocal,
        MethodModel method,
        string declaredType,
        string marshallingType,
        bool isOpcInterface,
        bool isUniquePointer,
        string targetLocal,
        string responsePayloadLocal,
        string responseSpanLocal)
    {
        if (isOpcInterface || IsOpcInterfaceRefType(marshallingType))
        {
            // [out, iid_is(riid)] LPUNKNOWN *ppUnk: a unique pointer to an
            // MInterfacePointer wrapper (MS-DCOM §2.2.1.10) containing an
            // OBJREF. Opt-in via [OpcUniquePointer] on the out/return symbol so
            // legacy "raw OBJREF on the wire" call paths (e.g. inside our
            // loopback path which doesn't yet round-trip the wrapper) continue
            // to use the unwrapped codec.
            string interfaceRead = isUniquePointer
                ? FormatMInterfacePointerReadExpression(readerLocal, declaredType)
                : FormatInterfaceReadExpression(readerLocal, declaredType);
            sb.Append(statementIndent).Append("var ").Append(targetLocal).Append(" = ").Append(interfaceRead).AppendLine(";");
            return;
        }

        if (TryGetCodec(marshallingType, method.DeclaringNamespace, out var codec))
        {
            if (codec.IsArray)
            {
                // [out] T** with size_is(,cIids) — unique pointer to a conformant
                // array. Wire is [referent][max_count][elements...]. The array
                // helper handles max_count + elements; emit the referent skip
                // here when the parameter/return carries [OpcUniquePointer].
                if (isUniquePointer)
                {
                    sb.Append(statementIndent).Append(readerLocal).AppendLine(".TryReadReferentId(out _);");
                }
                EmitArrayCodecReadLocal(
                    sb,
                    statementIndent,
                    readerLocal,
                    codec,
                    method.ParameterNames,
                    targetLocal,
                    responsePayloadLocal,
                    responseSpanLocal);
                return;
            }

            // Per MS-RPCE NDR §14.3.10, an [out] pointer-to-struct on the response
            // wire is prefixed by a 4-byte unique-pointer referent ID when declared
            // as [out] T** in IDL (e.g. IOPCServer::GetStatus's ppServerStatus).
            // Methods opt-in via [return: OpcUniquePointer] or per-out-parameter
            // [OpcUniquePointer]. Plain [out] T* reference pointers (the default for
            // scalar/struct out args) have no referent prefix.
            if (isUniquePointer)
            {
                sb.Append(statementIndent).Append(readerLocal).AppendLine(".TryReadReferentId(out _);");
            }
            sb.Append(statementIndent).Append("var ").Append(targetLocal).Append(" = ")
                .Append(FormatReadExpression(codec, readerLocal)).AppendLine(";");
            return;
        }

        sb.Append(statementIndent).Append(declaredType).Append(' ').Append(targetLocal).AppendLine(" = default!;");
    }

    private static void EmitArrayCodecReadLocal(
        StringBuilder sb,
        string statementIndent,
        string readerLocal,
        CodecEmitter codec,
        ImmutableArray<string> parameterNames,
        string targetLocal,
        string responsePayloadLocal,
        string responseSpanLocal)
    {
        string countLocal = UniqueLocalName(parameterNames, targetLocal + "Count", readerLocal, responsePayloadLocal, responseSpanLocal, targetLocal);
        string arrayLocal = UniqueLocalName(parameterNames, targetLocal + "Array", readerLocal, responsePayloadLocal, responseSpanLocal, targetLocal, countLocal);
        string indexLocal = UniqueLocalName(parameterNames, targetLocal + "Index", readerLocal, responsePayloadLocal, responseSpanLocal, targetLocal, countLocal, arrayLocal);

        sb.Append(statementIndent).Append("var ").Append(countLocal).Append(" = (int)").Append(readerLocal).AppendLine(".ReadUInt32();");
        sb.Append(statementIndent).Append("var ").Append(arrayLocal).Append(" = new ").Append(codec.ArrayElementType!).Append('[').Append(countLocal).AppendLine("];");
        sb.Append(statementIndent).Append("for (int ").Append(indexLocal).Append(" = 0; ").Append(indexLocal).Append(" < ").Append(countLocal).Append("; ").Append(indexLocal).AppendLine("++)");
        sb.Append(statementIndent).AppendLine("{");
        sb.Append(statementIndent).Append("    ").Append(arrayLocal).Append('[').Append(indexLocal).Append("] = ").Append(FormatReadExpression(codec, readerLocal)).AppendLine(";");
        sb.Append(statementIndent).AppendLine("}");
        sb.Append(statementIndent).Append("var ").Append(targetLocal).Append(" = ").Append(arrayLocal).AppendLine(";");
    }

    private static bool CanReadType(string typeName, bool isOpcInterface, string? declaringNamespace) =>
        isOpcInterface || IsOpcInterfaceRefType(typeName) || TryGetCodec(typeName, declaringNamespace, out _);

