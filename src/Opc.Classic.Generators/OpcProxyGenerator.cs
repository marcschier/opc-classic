    /// Marks an [in] array parameter as carrying a separate explicit
    /// <c>[in] DWORD N</c> sibling count field that the generator must emit
    /// before the array. The wire layout becomes <c>[count (4 bytes)] [array
    /// max_count (4 bytes)] [elements]</c> — the count appears twice (once as
    /// the standalone field, once as the array's NDR conformance header),
    /// matching IDL signatures like
    /// <c>[in] DWORD dwCount, [in, size_is(dwCount)] T* arr</c> (used by
    /// IOPCItemIO::Read, IOPCSyncIO::Read, IOPCItemMgt::AddItems, etc.).
