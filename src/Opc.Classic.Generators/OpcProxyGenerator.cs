    /// <summary>
    /// Marks a method parameter as an NDR unique pointer (per DCE 1.1 NDR /
    /// MS-RPCE §2.2.5). The generator emits a 4-byte referent ID before the
    /// value on the wire: 0 for null/absent, 0x00020000 for present. This is
    /// the NDR shape for IDL [unique, in] T* parameters. Apply explicitly when
    /// the C# parameter type cannot carry the unique-pointer hint via
    /// nullability (e.g. when the parameter is a non-nullable struct, or a
    /// string with no null-distinguishing convention).
    ///
    /// Nullable value types (int?, float?, Guid?) imply this automatically.
    /// </summary>
